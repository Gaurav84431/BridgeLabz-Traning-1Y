public class While {
    public static void main(String[] args ) {
        System.out.println("Example of While \n");
        int i = 1;
    
    while(i<=20) {
        System.out.println(i + "");
        i++;
        
        
    }

    System.out.println("Example of Do-WHILE"); 
    int j = 0;
    do {
        System.out.println(j);
        j++;
    }
    while(j <= 20);

}



}


